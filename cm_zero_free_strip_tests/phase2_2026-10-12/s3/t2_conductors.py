"""t2: conductors and infinity types of the members of X_u (inserts.tex, Lemma lem:s3-labels (d), (e), (f)).

For many sixth-power-free rows u (split and inert primes with valuations j = 1..5, unit factors, factors at 2 and lambda)
and finite-order multipliers theta in a model group Theta_0 generated by the Kummer characters chi_.(lambda), chi_.(2),
chi_.(omega) (conductors supported on {2, lambda}), we compute by brute force the conductor of the Hecke character
inducing each member
    finite-order:  theta(n) chi_n(u)^sigma,                       sigma = +-1,
    CM:            alpha(n)^sigma theta(n) chi_n(u)^sigma,        sigma = +-1   (co-oriented),
using randomized local exponent search: f | 2^4 lam^6 prod pi^2 is assumed and the exponent at each prime is lowered while the
modulus stays valid (a modulus g is valid if psi((x)) = alpha(x)^{k sigma} for random x = 1 mod g; 50 samples each).

Claims
  S3-T2a (f)  every member is ramified to exponent exactly 1 at each prime pi | u, pi not over 6 (all j = 1..5):
              in particular p | f, psi*(p) = 0 there, and the member is nonprincipal ("physical-row ramification").
  S3-T2b (e)  exponent at 2 <= 3 and at lambda <= 4 for every member, hence f | 72 u' (u' = prod_{pi | u, pi not | 6} pi)
              and Q = N(f) <= 5184 N(u') <= 5184 N(u).  Falsifier: Q <= N(u') fails.
  S3-T2c (e)  CM member: exponents equal to those of the finite-order member theta chi(u)^sigma away from lambda, and
              lambda-exponent <= max(2, lambda-exponent of f_0); so f_CM | lcm(lam^2, f_0) and Q_CM <= 9 Q_0.
              Falsifier: 'f_CM = f_0' fails for some case.
  S3-T2d (d)  infinity type: the CM member satisfies psi((x)) = alpha(x)^sigma for x = 1 mod f (so for sigma = -1 the
              inducing character has infinity type zbar/|z| and lies in F_CM; for sigma = +1 its conjugate does).
              Falsifiers: target 1 (finite order) and target alpha^{-sigma} (wrong type) are invalid even modulo
              2^4 lam^6 prod pi^2.
  S3-T2e (a)  the conjugate label (conj theta, -sigma) gives the same conductor (conjugation preserves f) and
              conjugate values at good primary n (zero convention included).
"""
import os, sys, random, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from s3lib import *

t0 = time.time()
rng = random.Random(12345)
p7, p13, p19, p31 = (split_prime(p) for p in (7, 13, 19, 31))
p7b = prim_assoc(conj(p7))
i5 = (-5, 0)
OM = (0, 1)

ROWS = [  # (name, u_factors (good primes, j), unit/S-part multiplier)
    ("pi7", [(p7, 1)], (1, 0)),
    ("pi7^2", [(p7, 2)], (1, 0)),
    ("pi7^3", [(p7, 3)], (1, 0)),
    ("pi7^4", [(p7, 4)], (1, 0)),
    ("pi7^5", [(p7, 5)], (1, 0)),
    ("7=pi7*pi7bar", [(p7, 1), (p7b, 1)], (1, 0)),
    ("pi13^2*pi7", [(p13, 2), (p7, 1)], (1, 0)),
    ("-5 (inert)", [(i5, 1)], (1, 0)),
    ("(-5)^3", [(i5, 3)], (1, 0)),
    ("omega*pi19", [(p19, 1)], OM),
    ("-pi31^5", [(p31, 5)], (-1, 0)),
    ("lam*pi7", [(p7, 1)], LAM),
    ("2*pi13^4", [(p13, 4)], (2, 0)),
    ("lam^5*2^3*pi19^2", [(p19, 2)], mul(pw(LAM, 5), (8, 0))),
    ("omega (unit row, S-supported)", [], OM),
]
THETAS = [("1", ()), ("chi(lam)", ((LAM, 1),)), ("chi(2)", (((2, 0), 1),)), ("chi(omega)", ((OM, 1),)),
          ("chi(lam)chi(2)^2", ((LAM, 1), ((2, 0), 2))),
          ("chi(lam)^3chi(2)^2chi(-1)", ((LAM, 3), ((2, 0), 2), ((-1, 0), 1)))]

okA = okB = okC = okD = okE = True
falsB = True        # 'Q <= N(u')' holds everywhere?
falsC = True        # 'f_CM = f_0' holds everywhere?
drop = 0            # cases where the CM member is unramified at lambda
falsD = True        # some falsifier target valid?
maxratio = 0.0; maxratio_u = 0.0; max2 = 0; maxl = 0
rowsA = []; ncase = 0
for name, uf, unit in ROWS:
    for tname, th in THETAS:
        for sigma in (1, -1):
            fin = Member(uf, unit=unit, theta=th, sigma=sigma, k=0)
            cm = Member(uf, unit=unit, theta=th, sigma=sigma, k=1)
            r0 = conductor(fin, lambda x: 1, rng=rng)
            r1 = conductor(cm, lambda x, s=sigma: alpha(x)**s, rng=rng)
            ncase += 1
            if r0 is None or r1 is None:
                okD = False; rowsA.append(f"{name},{tname},{sigma}: no modulus"); continue
            e0, Q0, f0 = r0; e1, Q1, f1 = r1
            # (a) exponent exactly 1 at good primes of u
            for P, j in uf:
                if e0[str(P)] != 1 or e1[str(P)] != 1:
                    okA = False; rowsA.append(f"{name},{tname},{sigma}: exponent at {P} is {e0[str(P)]},{e1[str(P)]}")
            # (b) bounds at 2, lambda and Q <= 5184 N(u')
            for e in (e0, e1):
                max2 = max(max2, e[str((-2, 0))]); maxl = max(maxl, e[str(LAM)])
                if e[str((-2, 0))] > 3 or e[str(LAM)] > 4:
                    okB = False
            Nu1 = 1
            for P, j in uf:
                Nu1 *= N(P)
            Nu = N(cm.u)
            for Q in (Q0, Q1):
                maxratio = max(maxratio, Q/Nu1); maxratio_u = max(maxratio_u, Q/Nu)
                if Q > 5184*Nu1:
                    okB = False
                if Q > Nu1:
                    falsB = False
            # (c) CM vs finite
            for key in e0:
                if key != str(LAM) and e0[key] != e1[key]:
                    okC = False
            if e1[str(LAM)] > max(2, e0[str(LAM)]) or Q1 > 9*Q0:
                okC = False
            if e0 != e1:
                falsC = False
            if e1[str(LAM)] == 0:
                drop += 1
            # (d) falsifiers for the infinity type, at the generous modulus
            primes = [(-2, 0), LAM] + [P for P, _ in uf]
            big = modulus([4, 6] + [2]*len(uf), primes)
            if sample_valid(big, cm, lambda x: 1, rng) or sample_valid(big, cm, lambda x, s=sigma: alpha(x)**(-s), rng):
                falsD = False
            # (e) conjugate label: same conductor, conjugate values
            cc = cm.conj_member()
            r2 = conductor(cc, lambda x, s=-sigma: alpha(x)**s, rng=rng)
            if r2 is None or r2[1] != Q1:
                okE = False
            for _ in range(20):
                n = prim_assoc(add((1, 0), mul((6, 0), (rng.randint(-20, 20), rng.randint(-20, 20)))))
                if N(n) == 0 or not coprime_to(n, [LAM, (-2, 0)]):
                    continue
                if abs(cc(n) - cm(n).conjugate()) > 1e-9:
                    okE = False

report("S3-T2a", "lem:s3-labels(f)", "every member (finite and CM) has conductor exponent exactly 1 at each good prime of u",
       okA, f"{ncase} (row, theta, sigma) cases, j = 1..5; " + ("; ".join(rowsA[:5]) if rowsA else "no exception"),
       falsifier_failed=None)
report("S3-T2b", "lem:s3-labels(e)", "exponent at 2 <= 3, at lambda <= 4; Q <= 5184 N(u') for all members", okB,
       f"max exponent at 2: {max2}, at lambda: {maxl}; max Q/N(u') = {maxratio:.4g}, max Q/N(u) = {maxratio_u:.4g}; "
       f"falsifier 'Q <= N(u')' holds for all? {falsB}", falsifier_failed=not falsB)
report("S3-T2c", "lem:s3-labels(e)", "CM conductor = finite-order conductor away from lambda; lambda-exp <= max(2, .); "
       "Q_CM <= 9 Q_0", okC, f"{drop} cases where the CM member is unramified at lambda (alpha's ramification "
       f"cancelled by theta chi(u)); falsifier 'f_CM = f_0 always' holds? {falsC}", falsifier_failed=not falsC)
report("S3-T2d", "lem:s3-labels(d)", "CM members have infinity type alpha^sigma (sigma=-1: zbar/|z|, in F_CM)", okD,
       f"falsifiers (finite order / opposite type) valid for some case? {not falsD}", falsifier_failed=falsD)
report("S3-T2e", "lem:s3-labels(a)", "conjugate label (conj theta, -sigma): same conductor, conjugate values", okE,
       "checked with the conductor search and 20 random good primary n per case", falsifier_failed=None)
print(f"time {time.time() - t0:.1f}s")
summary()
