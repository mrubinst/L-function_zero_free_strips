"""d1: members of the label set X_u (Appendix D of the CM guide): the Euler product and Moebius inversion eq:d165 (D.6)
and the Hecke presentation eq:d167 (D.9) of a CM member.

Model (as in tests_cm/phase2_2026-10-12/s3, imported read-only): S = primes above 6, Theta_0 generated by the Kummer
characters chi_.(lambda), chi_.(2), chi_.(omega), chi_.(-1); row u = pi7 pi13^2; members
phi_{u,nu,sigma}(n) = alpha(n)^{k sigma} theta(n) chi_n(u)^sigma (k = 0 finite order, k = 1 CM), zero convention.

Claims
  T7-D6  eq:d165  for members (finite and CM, sigma = +-1) and s in {2.5+1.3i, 3-2i}:
           sum_{n good primary, q_n <= X} phi(n) q_n^{-s} = prod_{p good primary prime, q_p <= X} (1 - phi(p) q_p^{-s})^{-1}
           and  (sum_n phi(n) q_n^{-s}) (sum_n mu(n) phi(n) q_n^{-s}) = 1, X = 30000 (tails < 1e-6).
           phi(n) is evaluated directly from the definition (residue symbols of n, not from phi on primes).
           Falsifiers: (1 + phi(p) q^{-s})^{-1} in the product; mu omitted in the inverse series.
  T7-D9  eq:d167  for finite-order members phi_0 = theta chi_.(u)^sigma with conductor f_0 (s3lib.conductor), m = lcm(f_0, 3):
           (1) a = eps_a a' (a' primary): alpha(a')^sigma = (a/|a|)^sigma eps_a^{-sigma}; eps_a depends only on a mod 3 and
               eps_{ab} = eps_a eps_b;
           (2) phi_{0,f}(a) := phi_0^*((a)) = phi_0(a') depends only on a mod f_0;
           (3) phi((a)) := alpha(a')^sigma phi_0^*((a)) = (a/|a|)^sigma eps_a^{-sigma} phi_{0,f}(a) is independent of the
               generator (all six associates), has phi((x)) = (x/|x|)^sigma for x = 1 mod m (infinity type), and equals the
               CM member alpha(n)^sigma theta(n) chi_n(u)^sigma at good primary n prime to u.
           Falsifiers: eps_a^{+sigma}, or no eps_a: the second expression depends on the generator.
"""
import os, sys, math, cmath, random, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from t7lib import report, finish, TESTS
sys.path.insert(0, os.path.join(TESTS, "phase2_2026-10-12", "s3"))
import s3lib
from s3lib import (Member, conductor, split_prime, factor_elt, alpha, mul, conj, N, cx, divides, sub, add, primary,
                   prim_assoc, UNITS, LAM, coprime_to, pw, modulus)

t0 = time.time()
rng = random.Random(1013)
p7, p13 = split_prime(7), split_prime(13)
U_F = [(p7, 1), (p13, 2)]
X = 30000

# good primary n (coprime to 6) with q_n <= X, with Moebius values and primality
R = int(math.isqrt(4 * X // 3)) + 3
goods = []
for a in range(-R, R + 1):
    for b in range(-R, R + 1):
        n = (a, b)
        q = N(n)
        if 1 <= q <= X and primary(n) and coprime_to(n, [LAM, (-2, 0)]):
            goods.append(n)
fac = {n: factor_elt(n) for n in goods}
mu = {n: (0 if any(e > 1 for _, e in fac[n]) else (-1) ** len(fac[n])) for n in goods}
isprime = {n: (len(fac[n]) == 1 and fac[n][0][1] == 1) for n in goods}
print(f"   {len(goods)} good primary n with q_n <= {X} ({time.time() - t0:.0f}s)", flush=True)

MEMBERS = [("finite theta=1, sigma=+1", (), 1, 0), ("finite chi(lam)chi(2)^2, sigma=-1", ((LAM, 1), ((2, 0), 2)), -1, 0),
           ("CM abar chi(lam) chibar(u) (denominator type), sigma=-1", ((LAM, 1),), -1, 1),
           ("CM alpha chi(2)chi(-1) chi(u), sigma=+1", (((2, 0), 1), ((-1, 0), 1)), 1, 1)]
d6_err = 0.0; d6_f1 = 1e9; d6_f2 = 1e9
for name, th, sg, k in MEMBERS:
    m = Member(U_F, theta=th, sigma=sg, k=k)
    vals = {n: m(n) for n in goods}
    for s in (complex(2.5, 1.3), complex(3, -2)):
        Lsum = sum(v * N(n) ** (-s) for n, v in vals.items())
        inv = sum(mu[n] * v * N(n) ** (-s) for n, v in vals.items() if mu[n])
        inv_f = sum(v * N(n) ** (-s) for n, v in vals.items() if mu[n])          # falsifier: mu omitted
        E = 1 + 0j; Ef = 1 + 0j
        for n, v in vals.items():
            if isprime[n]:
                E /= (1 - v * N(n) ** (-s))
                Ef /= (1 + v * N(n) ** (-s))
        d6_err = max(d6_err, abs(Lsum - E), abs(Lsum * inv - 1))
        d6_f1 = min(d6_f1, abs(Lsum - Ef))
        d6_f2 = min(d6_f2, abs(Lsum * inv_f - 1))
report("T7-D6", "eq:d165", "L_orig(s,phi) = prod_p (1 - phi(p) q_p^-s)^-1 and 1/L_orig = sum mu(n) phi(n) q_n^-s",
       d6_err < 1e-6, f"4 members (finite/CM, sigma = +-1) x 2 s, q_n <= {X}: max error {d6_err:.1e}; falsifiers: "
       f"(1 + phi(p)q^-s)^-1 min error {d6_f1:.2e}, mu omitted min error {d6_f2:.2e}",
       falsifier_failed=(d6_f1 > 1e-4 and d6_f2 > 1e-4))


# ---------------------------------------------------------------- D9
def eps_of(a):
    """the unit eps_a with a = eps_a a', a' primary (a coprime to 3): eps_a = unit congruent to a mod 3."""
    for u in UNITS:
        if divides((3, 0), sub(a, u)):
            return u
    raise ValueError(a)


def div_unit(a, u):
    return mul(a, conj(u))         # a / u for a unit u (u^{-1} = conj u)


CASES = [("theta=1, sigma=-1", (), -1), ("chi(lam), sigma=-1", ((LAM, 1),), -1), ("chi(2)chi(-1), sigma=+1", (((2, 0), 1), ((-1, 0), 1)), 1),
         ("chi(lam)^3 chi(2)^2 chi(-1), sigma=+1", ((LAM, 3), ((2, 0), 2), ((-1, 0), 1)), 1)]
e1 = e2 = e3 = e4 = e5 = e6 = 0.0
f_plus = 1e9; f_none = 1e9
lines = []
for name, th, sg in CASES:
    m0 = Member(U_F, theta=th, sigma=sg, k=0)
    mcm = Member(U_F, theta=th, sigma=sg, k=1)
    ex, Q0, f0 = conductor(m0, lambda x: 1, rng=rng)
    primes = [(-2, 0), LAM, p7, p13]
    exps = [ex[str(P)] for P in primes]
    mexps = list(exps); mexps[1] = max(exps[1], 2)
    mm = modulus(mexps, primes)
    lines.append(f"{name}: f0 exponents {exps}, N(m) = {N(mm)}")
    bad = [(-2, 0), LAM, p7, p13]

    def phi0f(a):
        e = eps_of(a)
        return m0(div_unit(a, e))           # phi_0^*((a)) = phi_0(a'), a' good primary prime to u

    def phi_first(a):
        e = eps_of(a)
        ap = div_unit(a, e)
        return alpha(ap) ** sg * m0(ap)

    def phi_second(a, mode="ok"):
        e = eps_of(a)
        z = cx(a)
        ez = cx(e)
        if mode == "ok":
            ee = ez ** (-sg)
        elif mode == "plus":
            ee = ez ** sg
        else:
            ee = 1
        return (z / abs(z)) ** sg * ee * phi0f(a)

    cnt = 0
    while cnt < 400:
        a = (rng.randint(-200, 200), rng.randint(-200, 200))
        if N(a) == 0 or not coprime_to(a, bad):
            continue
        cnt += 1
        e = eps_of(a)
        ap = div_unit(a, e)
        assert primary(ap)
        e1 = max(e1, abs(alpha(ap) ** sg - (cx(a) / abs(cx(a))) ** sg * cx(e) ** (-sg)))
        # eps depends only on a mod 3, multiplicative
        y = (rng.randint(-30, 30), rng.randint(-30, 30))
        e5 = max(e5, 0 if eps_of(add(a, mul((3, 0), y))) == e else 1)
        b = (rng.randint(-50, 50), rng.randint(-50, 50))
        if N(b) and coprime_to(b, [LAM]):
            e5 = max(e5, 0 if eps_of(mul(a, b)) == mul(e, eps_of(b)) else 1)
        # (2) phi_{0,f} depends only on a mod f0
        c = add(a, mul(f0, (rng.randint(-3, 3), rng.randint(-3, 3))))
        if N(c) and coprime_to(c, bad):
            e2 = max(e2, abs(phi0f(c) - phi0f(a)))
        # (3) the two expressions agree; generator independence
        v = phi_first(a)
        e3 = max(e3, abs(v - phi_second(a)))
        gp = gn = 0.0
        for u in UNITS:
            ua = mul(u, a)
            e3 = max(e3, abs(phi_second(ua) - v))
            gp = max(gp, abs(phi_second(ua, "plus") - phi_second(a, "plus")))
            gn = max(gn, abs(phi_second(ua, "none") - phi_second(a, "none")))
        f_plus = min(f_plus, gp) if gp > 0 else f_plus
        f_none = min(f_none, gn) if gn > 0 else f_none
    # infinity type on x = 1 mod m
    cnt = 0
    while cnt < 200:
        x = add((1, 0), mul(mm, (rng.randint(-20, 20), rng.randint(-20, 20))))
        if N(x) == 0 or not coprime_to(x, bad):
            continue
        cnt += 1
        z = cx(x)
        e4 = max(e4, abs(phi_second(x) - (z / abs(z)) ** sg))
    # agreement with the CM member on good primary n prime to u
    for n in goods[::40]:
        if coprime_to(n, [p7, p13]):
            e6 = max(e6, abs(phi_second(n) - mcm(n)))
for l in lines:
    print("   " + l)
report("T7-D9", "eq:d167", "phi((a)) = alpha(a')^sigma phi0*((a)) = (a/|a|)^sigma eps_a^-sigma phi0f(a): well defined, type (z/|z|)^sigma, = CM member",
       max(e1, e2, e3, e4, e5, e6) < 1e-9,
       f"4 finite-order phi_0 (sigma = +-1) x 400 random a: alpha(a') identity {e1:.1e}; eps_a mod-3/multiplicative failures {int(e5)}; "
       f"phi0f mod f0 {e2:.1e}; two expressions and generator independence {e3:.1e}; x = 1 mod m: {e4:.1e}; = CM member {e6:.1e}; "
       f"falsifiers (generator dependence, min over a with a nonzero value): eps^(+sigma) {f_plus:.2f}, no eps {f_none:.2f}",
       falsifier_failed=(f_plus > 0.5 and f_none > 0.5))
print(f"time {time.time() - t0:.1f}s")
finish()
